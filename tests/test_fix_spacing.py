@pytest.mark.parametrize("text,expect", MUST_FIX)
def test_fixes_broken_spacing(text, expect):
    assert expect in fix_spacing(text)


@pytest.mark.parametrize("text", MUST_KEEP)
def test_keeps_correct_text(text):
    assert fix_spacing(text) == text


@pytest.mark.parametrize("text,watch", REAL_PARAGRAPHS)
def test_real_paragraph_keeps_words(text, watch):
    out = fix_spacing(text)
    for w in watch:
        assert w in out, f"{w!r} 이(가) 쪼개졌다: {out}"


def test_only_whitespace_changes():
    for text, _ in MUST_FIX + [(t, None) for t in MUST_KEEP] + [(t, None) for t, _ in REAL_PARAGRAPHS]:
        assert "".join(fix_spacing(text).split()) == "".join(text.replace("\u00a0", " ").split())
